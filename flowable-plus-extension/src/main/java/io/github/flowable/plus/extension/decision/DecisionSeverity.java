package io.github.flowable.plus.extension.decision;

/**
 * 决策观测事实的严重度（ADR-0042 第 10 节「错误分类两轴」之一）。
 *
 * <p>由观测构造点<b>固定填入</b>，同时是<b>日志级别的唯一映射源</b>（级别 = 严重度直映）。三值与
 * 「是否进告警」的对应是契约，不是实现选择：</p>
 *
 * <ul>
 *   <li>{@link #ERROR} —— <b>进告警</b>：配置 / 契约问题需人介入（凭据失效 / 位点准入拒绝 /
 *       入站加工失败 / 内部错误 / 未物质化三情形）；</li>
 *   <li>{@link #WARN} —— <b>记录不告警</b>：可能瞬时（单次出站超时 / 非 2xx / 响应不可解析）；</li>
 *   <li>{@link #INFO} —— 正常记录（建议产出成功 / 按政策未产出）。</li>
 * </ul>
 *
 * <p>严重度<b>不进决策证据</b>：它是失败类别的观测轴派生，按命名宪章「派生概念不得落字段」只住
 * 日志与指标。</p>
 */
public enum DecisionSeverity {

    /** 进告警：配置 / 契约问题需人介入 */
    ERROR,

    /** 记录不告警：可能瞬时 */
    WARN,

    /** 正常记录 */
    INFO
}
